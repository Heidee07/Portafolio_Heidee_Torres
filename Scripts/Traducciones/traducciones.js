//___________________________________ Función para cambiar el idioma ___________________________________
function cambiarIdioma(idioma) {
    if (idioma === 'es') {
        document.getElementById('btn-es').classList.add('active');
        document.getElementById('btn-en').classList.remove('active');
    } else {
        document.getElementById('btn-en').classList.add('active');
        document.getElementById('btn-es').classList.remove('active');
    }

    localStorage.setItem('idioma', idioma);

    //Cookie para idioma
    document.cookie = "selectedLanguage=" + idioma + "; path=/";

    const elementos = document.querySelectorAll('[data-i18n]');

    elementos.forEach(elemento => {
        const llave = elemento.getAttribute('data-i18n');
        if (traducciones[idioma][llave]) {
            elemento.innerHTML = traducciones[idioma][llave];
        }
    });    
}

document.addEventListener('DOMContentLoaded', () => {
    const idiomaGuardado = localStorage.getItem('idioma') || 'es';
    cambiarIdioma(idiomaGuardado);   
});